  /**
   * One documented expression. `sql` is both what the table prints and what the check
   * compiles, except where `built` overrides it with the tree the optimizer hands Varka: an
   * `InSet`, which no SQL spelling produces directly because Spark's optimizer, not its parser,
   * creates it, and a row whose analyzed tree holds a cast no plan holds, which `optimized`
   * folds or unwraps. A row gives `executable` where `sql` is not the SQL to run, as the
   * `nullifzero(f)` row, whose resolved `sql` keeps the cast to DOUBLE for the suites that apply
   * no optimizer rule: SQL that a query can run and that the optimizer turns into the same
   * expression, so that `VarkaCoverageHarnessSuite` can run every row of the table. A row
   * without one runs `sql`.
   *
   * `domain` is the predicate inside which the row's kernel answers, for a row whose kernel can
   * decline a batch (VARKA-279 3.3): outside it the batch goes to the row engine, which answers
   * or raises as Spark does. A row with no guard has none, and the test below holds the two to
   * each other. Its bounds are rendered from the constants the emitter and the compiler read
   * (`VarkaChrono`, the lanes' ranges, the time guards' day), so a moved bound regenerates the
   * table rather than leaving it stale. Where the two modes differ it is ANSI's, the mode this
   * suite resolves the rows under (Spark's default): the checked int arithmetic and `make_date`'s
   * date check exist only there, and the legacy mode wraps or nulls as Spark does with no guard.
   */
  private case class Row(
      sql: String,
      note: String = "",
      built: Option[Expression] = None,
      executable: Option[String] = None,
      domain: Option[String] = None)

  private case class Family(title: String, predicates: Boolean, rows: Seq[Row])

  // --- the guarded rows' bounds, as SQL --------------------------------------------------------

  /** `INTERVAL 'y-m' YEAR TO MONTH` for a month count, with its sign ahead of the years. */
  private def ymLiteral(months: Long): String = {
    val magnitude = math.abs(months)
    s"INTERVAL '${if (months < 0) "-" else ""}${magnitude / 12}-${magnitude % 12}' YEAR TO MONTH"
  }

  private val dayLimit = VarkaChrono.INTERVAL_DAY_LIMIT_DAYS
  private val minMonths = VarkaChrono.MONTH_ARITH_MIN_MONTHS
  private val maxMonths = VarkaChrono.MONTH_ARITH_MAX_MONTHS

  /**
   * The note of a null test over an ordered comparison, which Spark's default
   * `NullDownPropagation` rewrites into null tests on the comparison's columns (VARKA-334).
   */
  private val pushedNote = "; a default session's NullDownPropagation pushes the test onto " +
    "the columns, so this form reaches Varka as written only with that rule excluded"

  /**
   * The column bound a calendar field's answer rests on (VARKA-379): the compiler guards the
   * column in the kernel, which declines a batch with a live day outside it (`VALUE_RANGE`).
   */
  private val dayBound =
    s"unix_date(d) BETWEEN ${VarkaChrono.CONTRACT_MIN_DAYS} AND ${VarkaChrono.CONTRACT_MAX_DAYS}"
  /** The largest count of a unit inside the day: the time conversions' range guard. */
  private def dayOf(nanosPerUnit: Long): Long = (NANOS_PER_DAY - 1) / nanosPerUnit
  /** The largest day count whose microseconds are a long: `date - date`'s range guard. */
  private val maxDateDiffDays = Long.MaxValue / MICROS_PER_DAY
  /** The days `CAST(d AS TIMESTAMP_NTZ)` converts without overflow: the cast's range guard. */
  private val ntzDayBound = s"unix_date(d) BETWEEN -$maxDateDiffDays AND $maxDateDiffDays"
  /**
   * The days of an NTZ value a calendar field answers for: the guard `ntzDay` puts on the date of
   * the count (VARKA-340), from 1 March -12799 to 15 August 33134. A day outside goes to the row
   * engine, which computes the field.
   */
  private val ntzFieldDays = "unix_date(CAST(ntz AS DATE)) BETWEEN " +
    s"${VarkaRangeAnalysis.NTZ_MIN_DAYS} AND ${VarkaChrono.NARROW_MAX_DAYS}"
  /**
   * The domain of an NTZ arithmetic row: unknown where an operand is null, and otherwise whether
   * Spark's `try_` form of the row has a value, which it has exactly where the row does not
   * raise. Spark's own arithmetic is the bound, since no SQL spells an NTZ value as its count.
   * A row whose kernel also guards one operand alone puts that guard first, `guard AND domain`:
   * the guard is false on that operand's value whatever the other operand holds, null included,
   * and three-valued AND keeps it false there.
   */
  private def ntzDomain(tried: String, operands: String*): String =
    s"if(${operands.map(_ + " IS NULL").mkString(" OR ")}, NULL, $tried IS NOT NULL)"

  /**
   * The domain of `timestampadd(unit, q, ntz)` up to a week (VARKA-339): Spark's sum with `q`
   * times the unit's interval, both tried, which is null exactly where `timestampadd` raises for
   * a quantity inside `guard`, the bound the kernel puts on `q` alone when it has one.
   */
  private def timestampAddDomain(unit: String, interval: String, q: String,
      guard: Option[Long]): Row = {
    val tried = ntzDomain(s"try_add(ntz, try_multiply($interval, $q))", "ntz", q)
    Row(s"timestampadd($unit, $q, ntz)", domain = Some(guard.fold(tried)(b =>
      s"$q BETWEEN -$b AND $b AND $tried")))
  }

  /** `timestampadd` by months, quarters or years: the date guard and the count's own. */
  private def timestampAddMonths(unit: String, k: Int, q: String): Row =
    Row(s"timestampadd($unit, $q, ntz)", domain = Some(s"$ntzFieldDays AND $q BETWEEN " +
      s"${Math.ceilDiv(minMonths, k)} AND ${Math.floorDiv(maxMonths, k)}"))

