  /**
   * The predicate rows of a floating column pair, `a` and `b`, whose literals carry `suffix`
   * (`D` or `F`, so that a literal is of the column's type and needs no cast): the comparisons,
   * `<=>`, `isnan`, the null tests, a literal on the right and `IN` in both its forms. The
   * column pairs meet NaN against NaN and against every other value, and both zeros both ways
   * round, in the differential fixtures. Both `IN` lists hold `0.0` and NaN, so the fixtures'
   * `-0.0` and NaNs of either sign are in them, as Spark's equality says.
   */
  private def floatingPredicates(a: String, b: String, suffix: String,
      dataType: DataType): Seq[Row] = {
    // SQL has no NaN literal: the cast is one the optimizer folds, as `VarkaSqlResolve` does.
    val nan = s"CAST('NaN' AS ${dataType.sql})"
    // The value of `v` in the column's type.
    def value(v: Double): Any = if (dataType == DoubleType) v else v.toFloat
    // Eleven literals of one integer digit or NaN, past the optimizer's InSet threshold of ten.
    val manyNumbers = (1 to 8).map(k => k + 0.5) ++ Seq(-2.5, 0.0)
    val many = manyNumbers.map(v => s"$v$suffix") :+ nan
    val manyValues: Set[Any] = (manyNumbers :+ Double.NaN).map(value).toSet
    val column = if (a == x.name) x else f
    Seq(
      Row(s"$a < $b"),
      Row(s"$a <= $b"),
      Row(s"$a > $b"),
      Row(s"$a >= $b"),
      Row(s"$a = $b", "NaN equals NaN, and -0.0 equals 0.0"),
      Row(s"$a <> $b"),
      Row(s"$a <=> $b", "null-safe equality under the lane's own equality"),
      Row(s"$a < 1.5$suffix", "the literal is its bits in the table of the lane's width; a "
        + "literal that is not NaN needs no NaN test, so this is the bare IEEE compare"),
      Row(s"$a = 1.5$suffix"),
      Row(s"$a <= 1.5$suffix"),
      Row(s"$a > 1.5$suffix", "the IEEE <= negated, so a NaN is above the literal"),
      Row(s"$a >= 0.0$suffix", "the IEEE < negated; -0.0 and 0.0 are one value"),
      Row(s"$a <> 0.0$suffix", "the IEEE = negated"),
      Row(s"1.5$suffix < $a", "a literal on the left is the swapped compare"),
      Row(s"$a = $nan", s"true where the IEEE $a <= Infinity is false, so NaN alone; no NaN test"),
      Row(s"$a < $nan", s"the IEEE $a <= Infinity: every value but NaN"),
      Row(s"$a IN (1.5$suffix, -2.5$suffix, 0.0$suffix, $nan)",
        "an equality chain under the lane's equality"),
      Row(s"$a IN (11 literals)",
        "an IN list this long arrives from the optimizer as an InSet and fuses the same way",
        Some(InSet(column, manyValues)), executable = Some(many.mkString(s"$a IN (", ", ", ")"))),
      Row(s"isnan($a)", "never null: false on a null row"),
      Row(s"$a IS NULL"),
      Row(s"$a IS NOT NULL"))
  }

  /** The value rows of a floating column pair: the picks, which move bits and order them. */
  private def floatingChoices(a: String, b: String): Seq[Row] = Seq(
    Row(s"greatest($a, $b)", "Spark's order, the first of two equal operands kept"),
    Row(s"least($a, $b)"),
    Row(s"nanvl($a, $b)", "an IF over isnan, null where the first operand is"),
    Row(s"CASE WHEN $a < $b THEN $a ELSE $b END"),
    Row(s"if($a IS NULL, $b, $a)"),
    Row(s"coalesce($a, $b)"))

  /**
   * The null family over one floating column pair (VARKA-578): the rewritten conditionals whose
   * null is the floating lane's own, a broadcast zero with its validity clear. `nullif` and
   * `nullifzero` compare under the lane's equality, so NaN equals NaN and -0.0 equals 0.0.
   */
  private def floatingNullFamily(a: String, b: String, zeroRows: Boolean): Seq[Row] = Seq(
    Row(s"nvl($a, $b)", s"rewritten to coalesce($a, $b)"),
    Row(s"ifnull($a, $b)"),
    Row(s"nvl2($a, $b, $a)", s"rewritten to if($a IS NOT NULL, $b, $a)"),
    Row(s"nullif($a, $b)", s"rewritten to if($a = $b, NULL, $a): NaN equals NaN and -0.0 equals "
      + "0.0, and the null is the lane's zero with its validity clear, so the kernel is "
      + "masked-only"),
    Row(s"CASE WHEN $a < $b THEN $a END", "the missing ELSE is the null of the floating lane"),
    Row(s"if($a IS NULL, $b, NULL)")) ++ (if (zeroRows) Seq(
    Row(s"nullifzero($a)", s"rewritten to if($a = 0, NULL, $a): -0.0 is zero, NaN is not"),
    Row(s"zeroifnull($a)", s"rewritten to coalesce($a, 0)")) else Seq.empty)

  /** The floating predicates of the null family: `BETWEEN` and `equal_null`. */
  private def floatingNullPredicates(a: String, b: String, suffix: String): Seq[Row] = Seq(
    Row(s"$a BETWEEN $b AND 5.5$suffix", "two comparisons in Spark's order and an AND: a NaN is "
      + "above every bound"),
    Row(s"equal_null($a, $b)", "rewritten to the null-safe equality, under the lane's equality"))

  /**
   * `sql` resolved and then folded and unwrapped as the optimizer does before Varka sees it
   * (`VarkaSqlResolve.optimizeIn`'s rules), for a row whose analyzed tree holds a cast that no
   * plan holds: a cast of a constant, or a widening compared with a literal.
   */
  private def optimized(sql: String): Expression =
    VarkaSqlResolve.optimizeIn(VarkaSqlResolve.parse(sql, columns), columns)

