  /**
   * The column's cell for one row, from what C2 printed for the row's kernel at 128 bits. A
   * `not supported` line is a refusal, and it names its construction; the census file carries
   * those lines alone, since C2's other two kinds prove nothing about the final code and vary
   * between runs (`VarkaWidthAuditSuite.isRefusal`, VARKA-154). The filter here is kept so a
   * census written before that change still renders the same column. A `declined` line is the
   * stronger answer - the emitter has no lowering for the row at that width, so no kernel ran
   * (VARKA-329) - and it is rendered with its reason.
   */
  private def narrowVerdict(sql: String): String = widthAudit match {
    case None => "not audited"
    case Some((_, narrow)) => narrow.get(sql) match {
      case None => "not audited"
      case Some(lines) =>
        val declined = lines.filter(_.startsWith("declined: ")).map(_.stripPrefix("declined: "))
        val refused = lines.filter(_.startsWith("not supported"))
        if (declined.nonEmpty) s"not emitted: ${declined.distinct.mkString(", ")}"
        else if (refused.isEmpty) "vector"
        else s"per-lane: ${refused.map(constructionOf).distinct.mkString(", ")}"
    }
  }

  /** The construction a `not supported` line is about, in words a reader of the table has. */
  private def constructionOf(line: String): String =
    if (line.contains("op=comp")) "compare to mask"
    else if (line.contains("op=blend")) "blend"
    else if (line.contains("op=cast")) "mask cast"
    else if (line.contains("op=broadcast") && line.contains("ismask=1")) "mask broadcast"
    else if (line.contains("op=test")) "mask test"
    else if (line.contains("is_masked_op=1")) "masked operation"
    else if (line.contains("ismask=1")) "mask logic"
    else if (line.contains("op=load") || line.contains("op=store")) "load or store"
    else "other"

  private def render(): String = {
    val sb = new StringBuilder
    widthAudit.foreach { case (host, _) =>
      sb.append("The *128-bit lanes* column is `sql/varka/width_audit.json`'s census on " +
        s"$host at a forced 128-bit species: `vector` means C2 refused no Vector API call in " +
        "the row's kernel there; `per-lane` names the constructions it had no lowering for, " +
        "which then run as Java loops over the lanes (VARKA-153). It is this x86 JVM's table " +
        "below its own width: the pool's aarch64 runner, whose native species is 128 bits, " +
        "refuses nothing (`VARKA-153.md` 6).\n\n")
    }
    sb.append("The *Switches* column names the family switches that keep the row off Varka, " +
      s"each `<name>` the setting `${VarkaFamily.SWITCH_PREFIX}<name>.enabled` (Configuration): " +
      "the families whose nodes the row's kernel holds, as the compiler records them for a " +
      "failure's `families:` line. A row with none compiles to a bare column read, which no " +
      "switch declines.\n\n")
    families.foreach { family =>
      sb.append(s"#### ${family.title}\n\n")
      sb.append(if (family.predicates) "| Predicate | Switches | Domain | Notes | 128-bit lanes |\n"
        else "| Expression | Switches | Domain | Notes | 128-bit lanes |\n")
      sb.append("|---|---|---|---|---|\n")
      // A cell's own `|`, as in `i | 4096`, is escaped, or the table reads it as a column break;
      // GitHub's tables take `\|` as a literal bar inside a code span as well.
      def cell(text: String): String = text.replace("|", "\\|")
      family.rows.foreach { r =>
        val domain = r.domain.map(d => s"`${cell(d)}`").getOrElse("")
        val switches = switchesOf(family, r) match {
          case Seq() => "none"
          case held => held.map(f => s"`${f.key}`").mkString(", ")
        }
        sb.append(s"| `${cell(r.sql)}` | $switches | $domain | ${cell(r.note)} | " +
          s"${narrowVerdict(r.sql)} |\n")
      }
      sb.append("\n")
    }
    sb.toString
  }

