    val sb = new StringBuilder("| Type | Rows | " + kinds.mkString(" | ") + " |\n")
    sb.append("| :--- |" + " ---: |" * (kinds.size + 1) + "\n")
    counts.keys.toSeq.sorted.foreach { t =>
      val c = counts(t)
      sb.append(s"| `$t` | ${c.values.sum} | " + kinds.map(k => c.getOrElse(k, 0)).mkString(" | ") +
        " |\n")
    }
    sb.toString
  }

