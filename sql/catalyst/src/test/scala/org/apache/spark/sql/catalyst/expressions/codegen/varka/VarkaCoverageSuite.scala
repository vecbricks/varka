  // --- what the table's kernels reach of the emitter (VARKA-280) ------------------------------

  /**
   * The emitter mechanisms the table's kernels reach and the ones they never do, read by row 265
   * beside the fuzzers' (`VarkaEmitReach`). Each row's kernels are emitted as `guardsOf` finds
   * them, under the defaults the table documents: a projection row's every kernel, a predicate
   * row's fused one; then every projection row as one projection and every predicate row as one
   * conjunction, the two widest shapes the table holds. "One kernel or several" is the compiler's
   * decision rather than the emitter's, so it is counted from the partial compile beside them.
   * Reported, not asserted; with `VARKA_REACH_DUMP` set to a directory the report is written
   * there as `VarkaCoverageSuite.md`.
   */
  test("the emitter mechanisms the table's kernels reach, and the ones they never do") {
    val options = VarkaEmitOptions.DEFAULTS
    val trace = new VarkaEmitTrace
    val reach = VarkaEmitReach.attach(trace, "coverage table")
    var compilations = 0
    var several = 0
    def projectionKernels(entries: Seq[NamedExpression]): Seq[CompiledVarkaProjection] = {
      val partial = VarkaExpressionCompiler.compilePartial(entries, columns, options).toScala
      compilations += 1
      if (partial.exists(!_.more.isEmpty)) several += 1
      partial.toSeq.flatMap(p => p.fused +: p.more.asScala.toSeq)
    }
    def predicateKernels(e: Expression): Seq[CompiledVarkaProjection] =
      VarkaExpressionCompiler.compilePredicate(e, columns, options).toScala.map(_.fused).toSeq
    val projections = families.filterNot(_.predicates).flatMap(_.rows).map(expressionOf)
    val predicates = families.filter(_.predicates).flatMap(_.rows).map(expressionOf)
    val kernels = projections.flatMap(e => projectionKernels(Seq(out(e)))) ++
      predicates.flatMap(predicateKernels) ++
      projectionKernels(projections.zipWithIndex.map { case (e, k) =>
        Alias(e, s"c$k")(): NamedExpression
      }) ++
      predicateKernels(predicates.reduce(And(_, _)))
    try {
      kernels.foreach { k =>
        try {
          VarkaLoopEmitter.emitTraced("org.apache.spark.sql.varka.execution.VarkaCoverageReach",
            k.outputs, k.inputOrdinals.size, k.numLiterals, options, trace)
        } catch {
          // A decline is an emission the trace has noted; the table's kernels are built to fit.
          case _: VarkaEmitDeclined =>
        }
      }
    } finally {
      VarkaEmitReach.detach(trace)
    }
    reach.lines.asScala.foreach(info(_))
    info(s"$several of $compilations projection compilations needed more than one kernel")
    assert(reach.emissions == kernels.size,
      s"${reach.emissions} emissions noted of ${kernels.size}")
    val provenance = "Generated by `VarkaCoverageSuite` with `VARKA_REACH_DUMP` set (VARKA-280): " +
      s"the kernels of the coverage table's ${projections.size} projection rows and " +
      s"${predicates.size} predicate rows, each alone, then all projection rows as one " +
      s"projection and all predicate rows as one conjunction, under the defaults. $several of " +
      s"$compilations projection compilations needed more than one kernel. Do not edit; " +
      "regenerate with `VARKA_REACH_DUMP=$PWD/sql/varka/coverage/reach build/sbt " +
      "'catalyst/testOnly *VarkaCoverageSuite'`."
    VarkaEmitReach.dump("VarkaCoverageSuite.md", "What the coverage table's kernels reached",
      provenance, java.util.List.of(reach)).ifPresent(p => logInfo(s"reach report written to $p"))
  }

  // --- the compiler's own list ------------------------------------------------------------

  /**
   * The Catalyst expression classes the compiler matches on, read from its source because there
   * is no runtime list to ask: the arms are a `match`, not a registry. The arms live in
   * `VarkaExpressionCompiler`, in `VarkaNodeCompiler` (the date leaves and the int arithmetic)
   * and in the four families it chains, so all six files are read. All six are Java: each
   * matches in a `switch`, whose type patterns (`case Add a`) and `instanceof` tests are what
   * name its classes.
   *
   * Every pattern naming a capitalised type is collected, then kept only if it names a real
   * class in `org.apache.spark.sql.catalyst.expressions`. That filter is what removes the IR
   * nodes, the data types and the local extractors without a hand-maintained exclusion list.
   *
   * Comments are stripped first. A comment that quotes a pattern - "an arm matching
   * `case HoursOfTime(child)` would never fire" - is prose about an arm the compiler does not
   * have, and counting it would both fail this check and publish the class in `coverage.json`
   * as one Varka admits.
   */
  private lazy val admittedByCompiler: Set[String] = {
    val javaFiles = Seq("VarkaExpressionCompiler", "VarkaNodeCompiler", "VarkaIntervalCompiler",
      "VarkaTimeCompiler", "VarkaConditionCompiler", "VarkaChronoCompiler")
    def read(name: String): String =
      withoutComments(Files.readString(
        getWorkspaceFilePath("sql", "catalyst", "src", "main", "java",
          "org", "apache", "spark", "sql", "catalyst", "expressions", "codegen",
          s"$name.java")))
    val javaPatterns = Seq(
      """case\s+([A-Z]\w*)\s+\w+\s*(?:when\b|->)""".r,
      """instanceof\s+([A-Z]\w*)""".r)
    def scan(sources: Seq[String], patterns: Seq[scala.util.matching.Regex]): Seq[String] =
      patterns.flatMap(p => sources.flatMap(p.findAllMatchIn(_).map(_.group(1))))
    // A file the patterns do not recognise would drop its family from the scan while the
    // others kept the total above the floor below, so each is checked on its own.
    val javaNames = javaFiles.map { f =>
      val found = scan(Seq(read(f)), javaPatterns)
      assert(found.nonEmpty, s"the Java pattern scan found no names in $f.java; do the " +
        "patterns still match how that file switches on expression classes?")
      found
    }
    val names = javaNames.flatten.toSet
    assert(names.size > 40, s"the pattern scan found only ${names.size} names; has the " +
      "compiler been restructured? This check is worthless if it silently matches nothing.")
    names.filter { n =>
      Try(Utils.classForName(s"org.apache.spark.sql.catalyst.expressions.$n"))
        .map(classOf[Expression].isAssignableFrom).getOrElse(false)
    }
  }

  /**
   * Scala or Java source with its block and line comments removed, so that a pattern scan reads
   * code and not prose about code. Newlines are kept, so nothing on a later line joins an
   * earlier one and forms a pattern neither of them wrote.
   */
  private def withoutComments(source: String): String =
    source
      .replaceAll("""(?s)/\*.*?\*/""", "")
      .replaceAll("""(?m)//.*$""", "")

  /**
   * Matched by the compiler but not expressions a reader writes: `Alias` wraps every
   * projection entry, `BoundReference` is what a column becomes once bound, `Literal` is a
   * constant inside another row, and `RuntimeReplaceable` is a trait the compiler unwraps.
   */
  private val infrastructure =
    Set("Alias", "BoundReference", "Literal", "RuntimeReplaceable")

  /**
   * Expressions the compiler matches only in order to decline them with a specific reason.
   *
   * <p>They are not coverage - nothing fuses, so a row in the table would be a false claim -
   * but a {@code case} exists for each so that the decline names the real blocker rather than
   * reading as "unsupported expression", which would send a reader looking in the wrong place.
   * The value is what blocks it. The test below keeps the list honest: anything here that
   * starts fusing fails, so this cannot become a place to park work that has since landed.
   */
  private val matchedOnlyToDecline = Map(
    "ExtractANSIIntervalMonths" ->
      "the result is a ByteType, and Varka has neither a byte lane nor an Arrow vector for one")

  // --- how each row is verified (VARKA-490) ----------------------------------------------------

  /**
   * How a row's kernel is verified beyond the differential suites every row runs in: a section
   * of `sql/varka/proofs/refinement.smt2` that refines it against the specification, a lowering
