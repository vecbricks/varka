  /**
   * The same rows as JSON, through Jackson rather than string building so that a quote or a
   * backslash in a future row cannot produce a file that parses as something else.
   *
   * `LinkedHashMap` throughout: the output has to be byte-identical between runs or the check
   * above would fail on ordering alone.
   */
  private def renderJson(): String = {
    def ordered(pairs: (String, Any)*): java.util.LinkedHashMap[String, Any] = {
      val map = new java.util.LinkedHashMap[String, Any]()
      pairs.foreach { case (k, v) => map.put(k, v) }
      map
    }
    val rows = families.flatMap { family =>
      family.rows.map { row =>
        // The column references and the constants are in every row and identify nothing, so
        // the list carries only the classes that decide whether a row is covered.
        val classes = expressionOf(row)
          .collect { case e: Expression => e.getClass.getSimpleName }
          .filterNot(infrastructure.contains)
          .filterNot(_ == "AttributeReference")
        ordered(
          "sql" -> row.sql,
          "executable" -> row.executable.getOrElse(row.sql),
          "family" -> family.title,
          "form" -> (if (family.predicates) "predicate" else "projection"),
          "catalyst" -> classes.distinct.sorted.asJava,
          "casts" -> castsOf(row).asJava,
          "operands" -> operandsOf(row).asJava,
          "switches" -> switchesOf(family, row).map(_.switchKey).asJava,
          "domain" -> row.domain.getOrElse(""),
          "note" -> row.note,
          "verified" -> verifiedOf(family, row).render)
      }
    }
    val doc = ordered(
      "generated_by" -> ("VarkaCoverageSuite; regenerate with VARKA_COVERAGE_REGEN=true " +
        "build/sbt 'catalyst/testOnly *VarkaCoverageSuite'"),
      "description" -> ("Every expression the Varka compiler fuses, with the Catalyst " +
        "expression classes each one resolves to. Anything absent runs on Spark's row engine. " +
        "A row whose kernel can decline a batch names its domain, the predicate inside which " +
        "the kernel answers (under ANSI where the modes differ); outside it the batch goes to " +
        "the row engine. An empty domain means every input of the column types is answered. " +
        "The switches are the family settings that keep the row off Varka, the families whose " +
        "nodes its kernel holds; empty for a row that compiles to a bare column read."),
      // Each column's type as SQL, which the readers parse back (`VarkaCoverageRows.read`).
      "columns" -> ordered(
        columns.map(a => a.name -> a.dataType.sql.toLowerCase(java.util.Locale.ROOT)): _*),
      "expressions" -> rows.asJava,
      "catalyst_classes_admitted" -> (admittedByCompiler -- infrastructure).toSeq.sorted.asJava)
    new ObjectMapper().writerWithDefaultPrettyPrinter().writeValueAsString(doc) + "\n"
  }

  /** A type's name in milestone 8's census and cast matrix, if any: the type registry's. */
  private def censusType(t: DataType): Option[String] =
    VarkaTypes.of(t).toScala.flatMap(id => Option(VarkaTypes.info(id).census))

  /**
   * The operand types of each class in a row, as `Class:type` in the census's type names: what
   * the census credits a class with (VARKA-328). A class is credited only with the types its own
   * node takes, so `year(d) = 2021 AND i > 0` credits `Year` with a date and the comparisons with
   * an int, where the column types the whole row reads would credit `Year` with the int as well.
   * A `BOOLEAN` operand is credited only where it is a boolean column: an `AND`'s or an `IF`'s
   * condition that is a comparison would otherwise let a `bool` claim pass with no boolean column
   * in the row, while `b = b2` and `NOT b` are what row 331 fuses over one (VARKA-484).
   */
  private def operandsOf(row: Row): Seq[String] = expressionOf(row).collect {
    case e: Expression if !infrastructure.contains(e.getClass.getSimpleName) =>
      // A class that inherits its analysis from its replacement keeps its own arguments as
      // `parameters`: `extract(YEAR FROM ym)` takes the interval, not what its replacement does.
      val operands = e match {
        case r: InheritAnalysisRules => r.parameters
        case _ => e.children
      }
      operands.flatMap(c => censusType(c.dataType).filter(t => t != "bool" ||
          c.isInstanceOf[Attribute]))
        .map(t => s"${e.getClass.getSimpleName}:$t")
  }.flatten.distinct.sorted

  /**
   * The casts a row performs, as `from>to:mode` in the census's type names: what the census holds
   * each pair `m8/casts.tsv` marks fused to (VARKA-328), since a cast's pair and mode are visible
   * only in the resolved expression, not in the class list. The mode is ANSI's for every row this
   * suite resolves, Spark's default. They are read before the current-time rewrite, which turns
   * `CAST(t AS TIMESTAMP_NTZ)` into the `make_timestamp_ntz` it compiles as (VARKA-340).
   */
  private def castsOf(row: Row): Seq[String] = {
    val written = row.built.getOrElse(VarkaSqlResolve.parseAsWritten(row.sql, columns))
    written.collect {
      case c: Cast => (censusType(c.child.dataType), censusType(c.dataType), c.evalMode)
    }.collect { case (Some(from), Some(to), mode) =>
      s"$from>$to:${mode.toString.toLowerCase(java.util.Locale.ROOT)}"
    }.distinct.sorted
  }

  private def between(text: String, marks: (String, String)): String = {
    val (beginMark, endMark) = marks
    val from = text.indexOf(beginMark)
    val to = text.indexOf(endMark)
    assert(from >= 0 && to > from, s"docs/sql-varka.md has no $beginMark ... $endMark block")
    text.substring(from + beginMark.length, to).stripPrefix("\n")
  }

  private def replaceBetween(text: String, marks: (String, String), body: String): String = {
    val (beginMark, endMark) = marks
    val from = text.indexOf(beginMark)
    val to = text.indexOf(endMark)
    text.substring(0, from + beginMark.length) + "\n" + body + text.substring(to)
  }

  /**
   * Every fusion decision the compiler makes over the table's rows, rendered as text, for a
   * refactor of the classifier to diff before and after (VARKA-300 2: the compiler suite is what
   * such a refactor rewrites, so it cannot be the refactor's only oracle). Opt-in, like the bytes
   * suite's option audit: set `VARKA_FUSION_DUMP` to a file and run this test on both sides.
   *
   * The rendering reads the model through its accessors and prints every component, so it does
   * not depend on how the model's types print. It covers each row as a projection, as `compile`
   * and, for a predicate row, as a predicate; all the rows together, with forwarded columns, with
   * a nondeterministic entry, and twice over; all the predicate rows as one conjunction; and the
   * several-kernel ladders and a projection over more columns than a kernel reads - under the
   * defaults, four method budgets alone, with several kernels and with condition splitting, fused
   * ceilings, and a forced residual.
   */
  test("the fusion decisions over the table, dumped for a refactor to diff " +
      "(opt-in: VARKA_FUSION_DUMP=<file>; VARKA-300)") {
    val target = sys.env.get("VARKA_FUSION_DUMP")
    import VarkaExpressionCompiler.{compile => compileAll, compilePartial, compilePredicate,
      declines => declinesOf, explainPredicate}
    assume(target.isDefined, "opt-in: set VARKA_FUSION_DUMP to a file")
    def projection(p: CompiledVarkaProjection): String = {
      val bounds = p.inputBounds.asScala.map(b => (b.inputIndex, b.lo, b.hi))
      val derived = p.derivedInputs.asScala.map(d => (d.inputIndex, d.sourceOrdinal, d.kind))
      val derivedAt = p.inputOrdinals.asScala.indices.map(i =>
        p.derivedAt(i).toScala.map(_.kind.toString).getOrElse("-"))
      s"outputs=${p.outputs.asScala.mkString("|")} types=${p.outputTypes.asScala.mkString("|")} " +
        s"in=${p.inputOrdinals.asScala.mkString(",")} lit=${p.literals.asScala.mkString(",")} " +
        s"bounds=${bounds.mkString("|")} derived=${derived.mkString("|")} " +
        s"longs=${p.longLiterals.asScala.mkString(",")} " +
        s"lane=${p.lane(VarkaEmitOptions.DEFAULTS)} n=${p.numLiterals} " +
        s"derivedAt=${derivedAt.mkString("|")}"
    }
    def spec(s: VarkaOutputSpec): String = s match {
      case f: FusedOutput => s"F${f.fusedIndex}"
      case k: KernelOutput => s"K${k.kernel}.${k.fusedIndex}"
      case w: ForwardedOutput => s"W${w.childOrdinal}"
      case _: ResidualOutput => "R"
      // scalac cannot check a match over a Java sealed interface; a new spec type fails here.
      case other => fail(s"unknown output spec $other")
    }
    // Both maps iterate in position order: the compiler returns a sorted one.
    def declines(m: java.util.Map[Integer, VarkaDecline]): String =
      m.asScala.toSeq.map { case (k, v) => (k.intValue, v) }.mkString("|")
    def partial(o: java.util.Optional[PartialVarkaProjection]): String =
      o.toScala.fold("None") { x =>
      val specs = x.specs.asScala
      s"specs=${specs.map(spec).mkString(",")} " +
        s"cols=${specs.map(x.columnIndex(_).orElse(-1)).mkString(",")} " +
        s"declines=${declines(x.declines)} " +
        s"fused=${projection(x.fused)} more=${x.more.asScala.map(projection).mkString(" || ")} " +
        s"kernels=${x.kernels.size}"
    }
    def conjunct(s: VarkaConjunctSpec): String =
      s"(${s.conjunct}, ${s.fused}, ${s.decline.toScala.getOrElse("-")})"
    def predicate(o: java.util.Optional[CompiledVarkaPredicate]): String =
      o.toScala.fold("None") { x =>
      s"specs=${x.specs.asScala.map(conjunct).mkString(",")} " +
        s"clauses=${x.clauses.asScala.map(_.asScala.mkString(",")).mkString(";")} " +
        s"fused=${projection(x.fused)} fc=${x.fusedConjuncts.asScala.mkString("|")} " +
        s"rc=${x.residualConjuncts.asScala.mkString("|")}"
    }
    val base = VarkaEmitOptions.DEFAULTS
    val optionSets = Seq("defaults" -> base) ++ Seq(120, 250, 500, 1000).flatMap { b =>
      Seq(s"budget$b" -> base.toBuilder().methodByteBudget(b).build(),
        s"several$b" -> base.toBuilder().severalKernels(true).methodByteBudget(b).build(),
        s"split$b" -> base.toBuilder().splitConditions(true).methodByteBudget(b).build())
    } ++ Seq(
      "ceiling" -> base.withFusedCeiling(3),
      "severalCeiling" -> base.toBuilder().severalKernels(true).build().withFusedCeiling(3),
      "severalCeiling8" -> base.toBuilder().severalKernels(true).build().withFusedCeiling(8),
      "force" -> base.toBuilder().forceResidualAt(2).build())
    val projections = families.filterNot(_.predicates).flatMap(_.rows).map(expressionOf)
    val predicates = families.filter(_.predicates).flatMap(_.rows).map(expressionOf)
    val sb = new StringBuilder
    for ((name, o) <- optionSets) {
      projections.foreach { e =>
        sb ++= s"$name P1 $e\n  ${partial(compilePartial(Seq(out(e)), columns, o))}\n"
        sb ++= s"  C ${compileAll(Seq(out(e)), columns, o).toScala.map(projection)}\n"
      }
      val all = projections.zipWithIndex.map { case (e, k) => Alias(e, s"c$k")(): NamedExpression }
      val withColumns = all ++ columns
      sb ++= s"$name PALL\n  ${partial(compilePartial(withColumns, columns, o))}\n"
      sb ++= s"  D ${declines(declinesOf(withColumns, columns, o))}\n"
      val random = withColumns :+ (Alias(Rand(Literal(1L)), "r")(): NamedExpression)
      sb ++= s"$name PRAND\n  ${partial(compilePartial(random, columns, o))}\n"
      sb ++= s"  D ${declines(declinesOf(random, columns, o))}\n"
      val twice = (all ++ all).zipWithIndex.map { case (n, k) =>
        Alias(n.children.head, s"d$k")(): NamedExpression
      }
      sb ++= s"$name PDUP\n  ${partial(compilePartial(twice, columns, o))}\n"
      predicates.foreach { e =>
        val q1 = compilePredicate(e, columns, o, VarkaAdmission.NO_HOST_REFUSAL)
        sb ++= s"$name Q1 $e\n  ${predicate(q1)}\n"
      }
      val conjunction = predicates.reduce(And(_, _))
      val qAll = compilePredicate(conjunction, columns, o, VarkaAdmission.NO_HOST_REFUSAL)
      sb ++= s"$name QALL\n  ${predicate(qAll)}\n"
      val explained = explainPredicate(conjunction, columns, o,
        VarkaAdmission.NO_HOST_REFUSAL).asScala
      sb ++= s"  E ${explained.map(conjunct).mkString(",")}\n"
    }
    def ladder(k: Int): NamedExpression =
      Alias(Greatest(Seq(AddMonths(d, Literal(k)), DateAdd(d, Literal(k)), LastDay(d))), "c")()
    val unrolled = VarkaMatrix.base.withDriverOutputTable(false)
    for (several <- Seq(false, true); n <- Seq(100, 200, 400)) {
      val o = unrolled.withSeveralKernels(several)
      val compiled = compilePartial((1 to n).map(ladder), columns, o)
      sb ++= s"LADDER $several $n\n  ${partial(compiled)}\n"
    }
    val dates = (0 until 70).map(c => AttributeReference(s"c$c", DateType)())
    val long = AttributeReference("l", LongType)()
    val wide = dates.map(c => Alias(DateAdd(c, Literal(1)), "o")(): NamedExpression) :+
      (Alias(Add(long, Literal(1L)), "o")(): NamedExpression)
    for (several <- Seq(false, true)) {
      val o = VarkaMatrix.base.withSeveralKernels(several)
      sb ++= s"WIDE $several\n  ${partial(compilePartial(wide, dates :+ long, o))}\n"
    }
    Files.writeString(java.nio.file.Path.of(target.get), sb.toString)
  }
