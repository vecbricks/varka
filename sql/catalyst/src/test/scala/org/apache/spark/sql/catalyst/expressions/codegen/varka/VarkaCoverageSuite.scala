  private def out(e: Expression): NamedExpression = Alias(e, "c")()

  /** The expression a row checks: its SQL resolved against `columns`, or its override. */
  private def expressionOf(row: Row): Expression =
    row.built.getOrElse(VarkaSqlResolve.resolve(
      org.apache.spark.sql.catalyst.parser.CatalystSqlParser.parseExpression(row.sql), columns))

  test("every documented expression compiles to a fused kernel") {
    val failures = families.flatMap { family =>
      family.rows.flatMap { row =>
        val expr = expressionOf(row)
        // The decline reason comes from the partial compile, which records one per entry. A
        // row that declines is a documentation bug, and the reason is what says which.
        val reason =
          if (family.predicates) {
            // Every conjunct has to fuse, not just one: the table documents the predicate as
            // written, and a residual conjunct runs in a row filter above the Varka node.
            VarkaExpressionCompiler.compilePredicate(expr, columns, VarkaEmitOptions.DEFAULTS,
              VarkaAdmission.NO_HOST_REFUSAL).toScala match {
              case Some(p) if p.specs.asScala.forall(_.fused) => None
              case Some(p) =>
                Some(p.specs.asScala.flatMap(_.decline.toScala).map(_.reason).mkString("; "))
              case None => Some("the predicate compiled to nothing")
            }
          } else {
            VarkaExpressionCompiler.compile(Seq(out(expr)), columns).toScala match {
              case Some(_) => None
              case None =>
                val partial = VarkaExpressionCompiler.compilePartial(Seq(out(expr)), columns)
                Some(partial.map(_.declines.asScala.values.map(_.reason).mkString("; "))
                  .orElse("no entry fused"))
            }
          }
        reason.map(r => s"${family.title}: ${row.sql}  ->  $r")
      }
    }
    assert(failures.isEmpty,
      "documented as covered, but the compiler declines:\n  " + failures.mkString("\n  "))
  }

  test("every predicate row compiles as a projection entry to a boolean output") {
    // VARKA-27 3.3: a predicate the compiler fuses as a filter is also an output, a BoolOutput
    // over the same condition, with no rule of its own. A bare boolean column is forwarded
    // instead, as every column is; alone it fuses nothing, and Spark's projection runs it.
    val rows = families.filter(_.predicates).flatMap(_.rows)
    val failures = rows.flatMap { row =>
      expressionOf(row) match {
        case _: AttributeReference =>
          VarkaExpressionCompiler.compilePartial(Seq(out(expressionOf(row))), columns).toScala
            .map(p => s"${row.sql}: a bare column compiled to $p").toSeq
        case expr =>
          VarkaExpressionCompiler.compile(Seq(out(expr)), columns).toScala match {
            case Some(p) if p.outputs.asScala.forall(_.isInstanceOf[VarkaVectorIR.BoolOutput])
                && p.outputTypes.asScala.forall(_ == BooleanType) => None
            case Some(p) => Some(s"${row.sql}: compiled to ${p.outputs.asScala.mkString(", ")}")
            case None => Some(s"${row.sql}: declines as an output: " +
              VarkaExpressionCompiler.declines(Seq(out(expr)), columns).asScala.values
                .map(_.reason).mkString("; "))
          }
      }
    }
    assert(failures.isEmpty, "predicate rows that are no boolean output:\n  " +
      failures.mkString("\n  "))
    assert(rows.size > 100, s"${rows.size} predicate rows")
  }

  // --- the guarded rows' domains ---------------------------------------------------------------

  /**
   * The guards a row's kernels carry, by name: each node the emitter refuses a batch at, by its
   * reason, and `INPUT_BOUND` where the compiler records a per-batch bound on an input column,
   * which the evaluator checks before the kernel runs (VARKA-279). Read under
   * `VarkaEmitOptions.DEFAULTS`, the options the rest of this suite compiles under, and not the
   * matrix's base: the table documents the engine as shipped, and a configuration that turns a
   * check off does not take a row's domain away.
   */
  private def guardsOf(family: Family, row: Row): Seq[String] = {
    kernelsOf(family, row).flatMap { k =>
      // A decimal leaf's slot check (VARKA-347) declines only a slot no value of the column's
      // type can be - Spark's reader raises on it, and Spark's writer never writes one - so it
      // has no domain inside the type to name, and is left out here.
      val refusals = VarkaLoopEmitter.guardsForTest(k.outputs, k.inputOrdinals.size,
        k.numLiterals, VarkaEmitOptions.DEFAULTS).asScala.values.map(_.reason.toString).toSeq
        .filterNot(_ == "DECIMAL_SLOT")
      refusals ++ k.inputBounds.asScala.map(_ => "INPUT_BOUND")
    }.distinct.sorted
  }

  /**
   * A row's kernels under `VarkaEmitOptions.DEFAULTS`: a predicate row's fused kernel, a
   * projection row's every kernel.
   */
  private def kernelsOf(family: Family, row: Row): Seq[CompiledVarkaProjection] = {
    val expr = expressionOf(row)
    val options = VarkaEmitOptions.DEFAULTS
    if (family.predicates) {
      VarkaExpressionCompiler.compilePredicate(expr, columns, options,
        VarkaAdmission.NO_HOST_REFUSAL).toScala.map(_.fused).toSeq
    } else {
      VarkaExpressionCompiler.compilePartial(Seq(out(expr)), columns, options).toScala.toSeq
        .flatMap(p => p.fused +: p.more.asScala.toSeq)
    }
  }

  /**
   * The family switches that keep a row off Varka (VARKA-318): the families whose nodes the
   * row's kernels hold, as the compiler records them for a failure's `families:` line, in
   * `VarkaFamily`'s order. `VarkaFamilySwitchSuite` holds that record to the families' claims on
   * the row's nodes and to what each switch declines, so the column cannot name a switch that
   * would not decline the row, nor miss one that would.
   */
  private def switchesOf(family: Family, row: Row): Seq[VarkaFamily] = {
    val held = kernelsOf(family, row).flatMap(_.families.asScala).toSet
    VarkaFamily.values().toSeq.filter(held.contains)
  }

  /**
   * What is wrong with the domains of `rows`: a row whose kernel carries a guard and names no
   * domain, a row that names one and carries no guard (a stale domain), and a domain that does
   * not resolve to a boolean over the table's columns, which would fail only in the sql/core
   * suite that runs it otherwise.
   */
  private def domainFindings(rows: Seq[(Family, Row)]): Seq[String] = rows.flatMap {
    case (family, row) =>
      val guards = guardsOf(family, row)
      (row.domain, guards) match {
        case (None, g) if g.nonEmpty =>
          Some(s"${row.sql}: carries ${g.mkString(", ")} and names no domain")
        case (Some(d), g) if g.isEmpty =>
          Some(s"${row.sql}: names the domain `$d` but carries no guard")
        case (Some(d), _) =>
          val resolved = Try(VarkaSqlResolve.resolve(CatalystSqlParser.parseExpression(d), columns))
          resolved.toEither match {
            case Right(e) if e.dataType == BooleanType && e.checkInputDataTypes().isSuccess =>
              None
            case Right(e) =>
              Some(s"${row.sql}: the domain `$d` is a ${e.dataType.sql}, not a boolean")
            case Left(t) => Some(s"${row.sql}: the domain `$d` does not resolve: ${t.getMessage}")
          }
        case _ => None
      }
  }

  test("every row whose kernel can decline a batch names its domain, and no other row does") {
    val all = families.flatMap(f => f.rows.map(f -> _))
    val findings = domainFindings(all)
    assert(findings.isEmpty,
      "the domain column disagrees with the guards the kernels carry:\n  " +
        findings.mkString("\n  "))
    // Counted, not assumed: rows on both sides, and the six reasons the table's rows carry all
    // represented somewhere, or the check would hold a table that carries no guard to nothing.
    val guarded = all.filter(_._2.domain.isDefined)
    assert(guarded.nonEmpty && guarded.size < all.size, s"${guarded.size} of ${all.size} guarded")
    val reasons = guarded.flatMap { case (f, r) => guardsOf(f, r) }.toSet
    assert(reasons == Set("DIVIDE_BY_ZERO", "INPUT_BOUND", "INT_OVERFLOW", "MAKE_DATE",
        "MONTH_COUNT", "VALUE_RANGE"),
      s"the guards the table's rows carry: $reasons")
    logInfo(s"${guarded.size} of ${all.size} rows carry a guard: " + guarded.map {
      case (f, r) => s"${r.sql} (${guardsOf(f, r).mkString(", ")})"
    }.mkString("; "))
  }

  test("a guarded row with no domain, a domain on a row with no guard, and a domain that is not " +
      "a boolean all fail the check") {
    val planted = Family("planted", predicates = false, Seq(
      Row("i + 1"),
      Row("dayofweek(d)", domain = Some("true")),
      Row("i - 1", domain = Some("i"))))
    val findings = domainFindings(planted.rows.map(planted -> _))
    def found(sql: String, ending: String): Boolean =
      findings.exists(f => f.startsWith(s"$sql:") && f.endsWith(ending))
    assert(found("i + 1", "names no domain"), findings)
    assert(found("dayofweek(d)", "carries no guard"), findings)
    assert(found("i - 1", "not a boolean"), findings)
    assert(findings.size == 3, findings)
  }

  test("every operand the compiler builds in a restricted position is one the position admits") {
    // VARKA-86. The emitter refuses an operand its position does not take, and a refusal at emit
    // time is a per-batch fallback while EXPLAIN claims fusion. So over every documented
    // expression, each operand the compiler built in a restricted position must be one the
    // position admits. The positions come from VarkaOperandPosition.restrictedOperands, the same
    // exhaustive function the emitter checks through, so this walk has no list of its own to go
    // stale. It checks what the compiler builds over the table, not that every arm asks the rule:
    // an arm that builds an admitted kind passes with or without its gate. Each position must be
    // reached, or the check would pass on nothing.
    val reached = scala.collection.mutable.Map.empty[VarkaOperandPosition, Int].withDefaultValue(0)
    val wrong = scala.collection.mutable.ArrayBuffer.empty[String]
    def walk(node: VarkaVectorIR, sql: String): Unit = {
      VarkaOperandPosition.restrictedOperands(node).asScala.foreach { r =>
        reached(r.position) += 1
        if (!r.position.admits(r.operand)) wrong += s"$sql: ${r.name} got ${r.operand}"
      }
      VarkaVectorIR.childrenOf(node).foreach(walk(_, sql))
    }
    families.foreach { family =>
      family.rows.foreach { row =>
        val expr = expressionOf(row)
        val outputs =
          if (family.predicates) {
            VarkaExpressionCompiler.compilePredicate(expr, columns, VarkaEmitOptions.DEFAULTS,
              VarkaAdmission.NO_HOST_REFUSAL).toScala.toSeq
              .flatMap(_.fused.outputs.asScala)
          } else {
            VarkaExpressionCompiler.compilePartial(Seq(out(expr)), columns).toScala.toSeq
              .flatMap(p => (p.fused +: p.more.asScala.toSeq).flatMap(_.outputs.asScala))
          }
        outputs.foreach(walk(_, row.sql))
      }
    }
    assert(wrong.isEmpty, wrong.mkString("\n"))
    // The trunc level is the exception: no documented expression truncates by a level column
    // (the table's trunc rows take literal levels), and its compiler arm builds the column with
    // the admitted Java type, so there is no built operand of that position to check here.
    VarkaOperandPosition.values().filter(_ != VarkaOperandPosition.TRUNC_LEVEL).foreach {
      position => assert(reached(position) > 0, s"no coverage row builds a $position operand")
    }
  }

