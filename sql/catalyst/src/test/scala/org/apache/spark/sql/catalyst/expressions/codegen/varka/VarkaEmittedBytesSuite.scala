  private val className = "org.apache.spark.sql.varka.execution.VarkaEmittedBytesOracle"

  private def sha(text: String): String = {
    val digest = MessageDigest.getInstance("SHA-256").digest(text.getBytes(StandardCharsets.UTF_8))
    digest.take(8).map(b => f"$b%02x").mkString
  }

  /**
   * What the emitted class is, hashed: one entry per method - its name and descriptor to the
   * hash of its rendered body, in declaration order - and one for the class around them, under
   * the key `<class>`, which no method entry can collide with because a method's key always
   * carries its descriptor's parentheses. The class entry covers what the bodies cannot: the
   * flags, the interfaces, the attribute names, and each method's own flags. Without it a
   * refactor could drop the `VarkaFusedKernel` interface or the telemetry attribute and every
   * body would still render identically.
   */
  /**
   * The options a shape is emitted with at `lanes`, the int lane's count: a long-lane shape at
   * the same width, which is half the lanes. The arm is applied over the width, not under it:
   * every arm leaves the lane count alone, and the oracle's two widths are what the arm is
   * compared across.
   */
  private def emitOptions(roots: Seq[VarkaVectorIR], lanes: Int,
      arm: VarkaEmitOptions => VarkaEmitOptions): VarkaEmitOptions = {
    val laneCount =
      // Half the lanes at every 64-bit drive, DOUBLE's included.
      if (VarkaKernelPlan.driveOf(roots.asJava, VarkaMatrix.base)
          .filter(_.bits() == java.lang.Long.SIZE).isPresent) {
        lanes / 2
      } else {
        lanes
      }
    arm(VarkaMatrix.base.withLanesOverride(laneCount))
  }

  private def methodHashes(roots: Seq[VarkaVectorIR], numInputs: Int, numLiterals: Int,
      lanes: Int,
      arm: VarkaEmitOptions => VarkaEmitOptions = identity): Seq[(String, String)] = {
    // `lanes` is the int lane's count, and names a width: 4 lanes are 128 bits and 16 are 512.
    // A long-lane shape is emitted at the same two widths, which are 2 and 8 of its lanes;
    // sixteen 64-bit lanes would be a species that does not exist, and the emitter would fall
    // back to SPECIES_PREFERRED and pin nothing about width. The lane asked for is the
    // emission's, which for a narrowing root (an int output computed in the long lane) is the
    // long lane.
    val options = emitOptions(roots, lanes, arm)
    // A narrow value the lane count cannot widen has no lowering, and the compiler refuses the
    // row before an emission (VARKA-329): a width that bakes no int lane count has no species to
    // name. Record the compiler's answer rather than a class that cannot link, as the arms'
    // declines are recorded below.
    val refusal = VarkaKernelPlan.refusalOf(roots.asJava, options)
    if (refusal.isPresent()) {
      return Seq("<declined>" -> sha(refusal.get()))
    }
    val bytes =
      try {
        VarkaLoopEmitter.emit(className, roots.asJava, numInputs, numLiterals, null, null, options)
      } catch {
        // An arm may decline a shape the defaults emit (VARKA-87's byte budget on a heavy single
        // output); the audit records that as the arm's answer rather than failing on it.
        case d: VarkaEmitDeclined => return Seq("<declined>" -> sha(d.getMessage))
        // The form without a byte budget, a pinned reference arm, caps a shape's distinct ops
        // (MAX_FUSED_NODES) and rejects one over it, which the defaults emit: the arm's answer
        // too. Any other rejection is a contract violation and fails the suite (VARKA-306).
        case e: IllegalArgumentException if options.methodByteBudget == 0 &&
            String.valueOf(e.getMessage).contains("MAX_FUSED_NODES") =>
          // A site's own text, not Spark's INTERNAL_ERROR framing around it (VARKA-314).
          return Seq("<rejected>" -> sha(Option(VarkaErrors.siteText(e)).getOrElse(e.getMessage)))
      }
    ("<class>" -> sha(VarkaEmitterTestSupport.classSummary(bytes))) +:
      VarkaEmitterTestSupport.methodBodies(bytes).asScala.toSeq.map { case (m, body) =>
        m -> sha(body)
      }
  }

  // ---------------------------------------------------------------------------------------
  // The coverage rows
  // ---------------------------------------------------------------------------------------

  private case class CoverageShape(sql: String, roots: Seq[VarkaVectorIR], numInputs: Int,
      numLiterals: Int)

  /**
   * The row as the optimizer would hand it to the compiler. There is no optimizer here - the SQL
   * is parsed and resolved and that is all - so a row the table records as arriving as an `InSet`
   * would otherwise be pinned through the compiler's `In` arm, which is not the arm production
   * takes. `OptimizeIn`'s rewrite is the only such difference the table has; the row's own
   * `catalyst` field says which rows it applies to.
   */
  private def asCatalystClaims(expr: Expression, catalyst: Set[String]): Expression = expr match {
    case In(value, list) if catalyst.contains("InSet") && list.forall(_.isInstanceOf[Literal]) =>
      InSet(value, list.map(_.asInstanceOf[Literal].value).toSet)
    case other if catalyst.contains("InSet") =>
      // The rewrite is the only thing standing between this row and the wrong compiler arm, so
      // a row that claims InSet and does not get one fails rather than being pinned quietly.
      fail(s"a row the table records as an InSet resolved to ${other.getClass.getSimpleName}: " +
        "the executable spelling and the catalyst field disagree")
    case other => other
  }

  /**
   * Every row of the table as IR, through the compiler: a projection row's compiled outputs, a
   * predicate row's fused condition root.
   *
   * Two ways a row can fail to produce IR, and they are not the same thing. A row whose SQL does
   * not parse is recorded as skipped, by name, so the file says what it does not pin; the table
   * carries an `executable` spelling for every row today, so the list is empty and a name
   * appearing in it is a table that grew a caption. A row that parses and then declines is a
   * coverage regression - `VarkaCoverageSuite` asserts every row fuses - so it fails here
   * rather than quietly moving into that list, where a regeneration would bless it.
   */
  private lazy val coverage: (Seq[CoverageShape], Seq[String]) = {
    val file = getWorkspaceFilePath("sql", "varka", "coverage.json").toFile
    val doc = new ObjectMapper().readTree(file)
    val shapes = Seq.newBuilder[CoverageShape]
    val skipped = Seq.newBuilder[String]
    doc.get("expressions").elements().asScala.foreach { e =>
      val sql = e.get("sql").asText()
      val executable = Option(e.get("executable")).map(_.asText()).getOrElse(sql)
      val form = e.get("form").asText()
      val catalyst = Option(e.get("catalyst"))
        .map(_.elements().asScala.map(_.asText()).toSet).getOrElse(Set.empty[String])
      // The parse guard covers the parse and the resolve, and nothing else: `asCatalystClaims`
      // fails the suite on purpose when a row's spelling and its catalyst field disagree, and a
      // catch around it would turn that into a silent skip.
      val parsed: Option[Expression] =
        try Some(VarkaSqlResolve.resolve(CatalystSqlParser.parseExpression(executable), columns))
        catch { case _: Exception => None }
      val resolved = parsed.map(asCatalystClaims(_, catalyst))
      val compiled = resolved.flatMap { expr =>
        if (form == "predicate") {
          VarkaExpressionCompiler.compilePredicate(expr, columns).toScala.map(_.fused)
        } else {
          VarkaExpressionCompiler.compile(Seq(Alias(expr, "c")()), columns).toScala
        }
      }
      compiled match {
        case Some(c) =>
          shapes += CoverageShape(sql, c.outputs.asScala.toSeq, c.inputOrdinals.size,
              c.numLiterals)
        case None if resolved.isEmpty => skipped += sql
        case None =>
          fail(s"coverage row does not fuse, so the oracle cannot pin it: $sql. " +
            "VarkaCoverageSuite asserts every row fuses; fix that first.")
      }
    }
    (shapes.result(), skipped.result())
  }

  // ---------------------------------------------------------------------------------------
  // The fuzz sequence
  // ---------------------------------------------------------------------------------------

  private case class FuzzShape(roots: Seq[VarkaVectorIR], numInputs: Int, numLiterals: Int)

  /**
   * Shape `k` of the sequence: `VarkaIrGrammar`'s draw, from `VarkaIrGrammar`'s seed, through
   * `VarkaIrGrammar`'s generator - all three shared with `VarkaIrFuzzSuite`, so shape `k` here
   * is shape `k` there. This suite pins ten thousand of them and that suite checks the first
   * three hundred against the reference evaluator by default, so the corpora are one sequence
   * with two depths rather than two sequences: every shape the fuzzer checks is pinned here,
   * and a shape beyond that prefix is one the fuzzer checks when its iteration count is raised.
   * Copies of the draw, the seed or the generator in each suite would let them part company
   * with no test noticing, which is why none of the three lives here.
   */
  private def fuzzShape(k: Int): FuzzShape = intShapes(k)

  /** The int sequence, drawn once per JVM: every pass reads it, twenty of them (VARKA-307). */
  private lazy val intShapes: IndexedSeq[FuzzShape] = (0 until shapes).map { k =>
    val drawn = drawShape(shapeRandom(seed, k))
    FuzzShape(drawn.roots.asScala.toSeq, drawn.numInputs, drawn.numLiterals)
  }

  /**
   * Shape `k` of the long-lane sequence, the same way: `VarkaIrGrammar`'s long draw from its
   * long seed, which `VarkaIrFuzzSuite` runs against `evalLong`.
   */
  private def longFuzzShape(k: Int): FuzzShape = longShapes(k)

  private lazy val longShapes: IndexedSeq[FuzzShape] = (0 until shapes).map { k =>
    val drawn = drawLongShape(shapeRandom(LONG_FUZZ_SEED, k))
    FuzzShape(drawn.roots.asScala.toSeq, drawn.numInputs, drawn.numLiterals)
  }

  /**
   * Shape `k` of the sequence of both lanes (VARKA-28): `VarkaIrGrammar`'s mixed draw from its
   * own seed, which `VarkaIrFuzzSuite` runs against `mixedValue`. A sequence of its own, so that
   * the two corpora above stay what they were.
   */
  private def mixedFuzzShape(k: Int): FuzzShape = mixedShapes(k)

  private lazy val mixedShapes: IndexedSeq[FuzzShape] = (0 until shapes).map { k =>
    val drawn = drawMixedShape(shapeRandom(MIXED_FUZZ_SEED, k))
    FuzzShape(drawn.roots.asScala.toSeq, drawn.numInputs, drawn.numLiterals)
  }

  /** The digest of one block of a sequence at one width. */
  private def blockDigest(shapeAt: Int => FuzzShape, block: Int, lanes: Int): String = {
    val sb = new StringBuilder
    for (k <- block * blockSize until math.min((block + 1) * blockSize, shapes)) {
      val s = shapeAt(k)
      sb.append(k).append(':')
      methodHashes(s.roots, s.numInputs, s.numLiterals, lanes).foreach { case (m, h) =>
        sb.append(' ').append(m).append('=').append(h)
      }
      sb.append('\n')
    }
    sha(sb.toString)
  }

  // ---------------------------------------------------------------------------------------
  // In parallel
  // ---------------------------------------------------------------------------------------

  /**
   * The threads the passes hash on: one per available processor, or `-Dvarka.bytes.threads`; at
   * 1 the suite is serial. Every shape's hashes are a function of the shape and the options, so
   * the passes split by shape, and the emitter holds no mutable state between emissions - which
   * the race test below would see if it stopped being true (VARKA-307).
   */
  private val threads =
    sys.props.get("varka.bytes.threads").map(_.toInt).getOrElse(availableProcessors)

  private def availableProcessors: Int = Runtime.getRuntime.availableProcessors

  private def newPool(size: Int): ExecutorService = Executors.newFixedThreadPool(size, r => {
    val t = new Thread(r, "varka-bytes-oracle")
    t.setDaemon(true)
    t
  })

  private lazy val pool = newPool(threads)

  /** `f` over `0 until n` on the suite's pool, in index order; serial at one thread. */
  private def inOrder[T](n: Int)(f: Int => T): IndexedSeq[T] =
    if (threads <= 1) (0 until n).map(f) else runOn(pool, n)(f)

  /**
   * `f` over `0 until n` on `executor`'s threads, the results in index order: a digest built
   * from them is the digest a serial loop builds. Called from the test's thread only, never from
   * a task, so no task waits on the pool it runs in. A task's failure is rethrown as its own
   * exception, so a contract violation fails the suite with the message it always had.
   */
  private def runOn[T](executor: ExecutorService, n: Int)(f: Int => T): IndexedSeq[T] = {
    val chunk = math.max(1, n / (availableProcessors * 8))
    val futures = (0 until n by chunk).map { from =>
      executor.submit(new Callable[IndexedSeq[T]] {
        override def call(): IndexedSeq[T] = (from until math.min(n, from + chunk)).map(f)
      })
    }
    futures.flatMap { future =>
      try future.get() catch { case e: ExecutionException => throw e.getCause }
    }
  }

  override def afterAll(): Unit = {
    try pool.shutdownNow() finally super.afterAll()
  }

  // ---------------------------------------------------------------------------------------
  // The file
  // ---------------------------------------------------------------------------------------

  /**
   * The emissions the oracle pins beyond the defaults: those a session can select, and two
   * reference forms whose frames span the kernel.
   *
   * Only one field of `VarkaEmitOptions` has a configuration in front of it -
   * `spark.sql.codegen.varka.emit.useAVX`, which VARKA-121 added so that a machine whose
   * converts do not become instructions can ask for the magic form. Everything else on the
   * record reaches the emitter through a test hook alone, and the audit test below records
   * which of those move bytes. The oracle therefore pins the defaults in full, shape by
   * shape, and each of these arms as one digest per width: a digest is enough to catch a
   * change, and pinning every arm shape by shape would multiply a large file by the arms to
   * say the same thing.
   *
   * A level the emitter treats as the default is pinned anyway. It costs a line and it is the
   * only way the file can show that `useAVX=3` and an unstated level really do emit alike.
   *
   * Beside them, both values of each option the defaults never reach, over the options under
   * which it acts (`VarkaEmitOption.Subject`, VARKA-247): `validityOrFirst` orders a per-group
   * validity OR the defaults do not emit, so at the defaults its two values are one emission and
   * a pin there would say nothing.
   *
   * And two reference forms no session selects, whose frames span the kernel rather than one
   * group (VARKA-306): `groupLocalSlots=false`, which plans every method's slots over the whole
   * kernel, and a byte budget of 0, whose single epilogue serves every output. A slot rule that
   * holds per body can still move their bytes, and once did unseen: VARKA-83's first scratch rule
   * moved 23 of 64 multi-group guarded cases in exactly these two (`VARKA-83.md` 9.1). The int
   * fuzz shapes below catch that rule in both arms at both widths.
   */
  private def pinnedArms: Seq[(String, VarkaEmitOptions => VarkaEmitOptions)] =
    Seq(VarkaEmitOptions.USE_AVX_UNKNOWN, 0, 1, 2, 3).map { level =>
      s"useAVX=$level" -> ((o: VarkaEmitOptions) => o.withUseAVX(level))
    } ++ subjectArms ++ laneArms ++ referenceArms

  /**
   * The narrow-lane option's two arms, both pinned (VARKA-329): the default arm is what the
   * per-row hashes above are emitted under, and the native arm is an emission no per-row hash
   * covers, since the rows there are the defaults'. A machine option has no session
   * configuration, so it is reachable from tests only, which is exactly why the oracle has to
   * pin it: a refactor of the narrow lane must move a hash here rather than slip through.
   */
  private def laneArms: Seq[(String, VarkaEmitOptions => VarkaEmitOptions)] =
    Seq("narrowLanes=true", "narrowLanes=false").map { name =>
      val arm = optionArms.find(_.name == name).getOrElse(
        fail(s"the options table has no arm $name to pin"))
      arm.name -> arm.arm
    }

  /**
   * The reference forms whose frames span the kernel, pinned beside the selectable arms: the
   * options table's own arms, by name, so the pin and the audit name the same emission.
   */
  private def referenceArms: Seq[(String, VarkaEmitOptions => VarkaEmitOptions)] =
    Seq("groupLocalSlots=false", "methodByteBudget=0").map { name =>
      val arm = optionArms.find(_.name == name).getOrElse(
        fail(s"the options table has no arm $name to pin"))
      arm.name -> arm.arm
    }

  /** The arms of every flag whose subject is not the defaults, applied over that subject. */
  private def subjectArms: Seq[(String, VarkaEmitOptions => VarkaEmitOptions)] =
    optionArms.collect { case AuditArm(name, arm, Some(_)) => name -> arm }

  /**
   * An arm as the audit and the pinned digests use it: the table's arm, applied over its option's
   * subject where that is not the defaults, and that subject, which the arm is compared against
   * so that the option's default is the arm that moves nothing (VARKA-247).
   */
  private case class AuditArm(name: String, arm: VarkaEmitOptions => VarkaEmitOptions,
      subject: Option[VarkaEmitOption.Subject])

  /** A flag's subject, unless it is the defaults. */
  private def subjectOf(option: VarkaEmitOption): Option[VarkaEmitOption.Subject] = option match {
    case f: VarkaEmitOption.Flag if f.subject() != VarkaEmitOption.Subject.DEFAULTS =>
      Some(f.subject())
    case _ => None
  }

  /** `a` over `subject`: the subject's options first, then the arm's own change. */
  private def over(a: VarkaEmitOption.Arm,
      subject: VarkaEmitOption.Subject): VarkaEmitOptions => VarkaEmitOptions =
    (o: VarkaEmitOptions) => a.apply.apply(subject.apply.apply(o))

  /** One hash over every shape the oracle holds, emitted under `arm` at `lanes`. */
  private def armDigest(arm: VarkaEmitOptions => VarkaEmitOptions, lanes: Int): String = {
    // One line per shape, each computed on the pool and joined in the order they were before.
    def line(label: String, roots: Seq[VarkaVectorIR], numInputs: Int, numLiterals: Int) = {
      val sb = new StringBuilder(label)
      methodHashes(roots, numInputs, numLiterals, lanes, arm).foreach { case (m, h) =>
        sb.append(' ').append(m).append('=').append(h)
      }
      sb.append('\n').toString
    }
    val (rows, _) = coverage
    val rowLines = inOrder(rows.size) { i =>
      val r = rows(i)
      line(r.sql, r.roots, r.numInputs, r.numLiterals)
    }
    val shapeLines = Seq(intShapes, longShapes, mixedShapes).flatMap { sequence =>
      inOrder(shapes) { k =>
        val sh = sequence(k)
        line(k.toString, sh.roots, sh.numInputs, sh.numLiterals)
      }
    }
    sha((rowLines ++ shapeLines).mkString)
  }

  private def render(): String = {
    def ordered(pairs: (String, Any)*): java.util.LinkedHashMap[String, Any] = {
      val map = new java.util.LinkedHashMap[String, Any]()
      pairs.foreach { case (k, v) => map.put(k, v) }
      map
    }
    val (rows, skipped) = coverage
    val perWidth = widths.map { lanes =>
      val coverageHashes = ordered(inOrder(rows.size) { i =>
        val r = rows(i)
        r.sql -> ordered(methodHashes(r.roots, r.numInputs, r.numLiterals, lanes): _*)
      }: _*)
      val blockCount = (shapes + blockSize - 1) / blockSize
      val blocks = inOrder(blockCount)(blockDigest(fuzzShape, _, lanes))
      val longBlocks = inOrder(blockCount)(blockDigest(longFuzzShape, _, lanes))
      val mixedBlocks = inOrder(blockCount)(blockDigest(mixedFuzzShape, _, lanes))
