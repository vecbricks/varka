package org.apache.spark.sql.varka.vector;

import static org.apache.spark.sql.varka.vector.VarkaVectorSupport.ofAddress;
import static org.apache.spark.sql.varka.vector.VarkaVectorSupport.orPartialValidityBitsAt;
import static org.apache.spark.sql.varka.vector.VarkaVectorSupport.orValidityBitsAt;
import static org.apache.spark.sql.varka.vector.VarkaVectorSupport.partialValidityBitsAt;
import static org.apache.spark.sql.varka.vector.VarkaVectorSupport.validityBitsAt;
import static org.apache.spark.sql.varka.vector.VarkaVectorSupport.zero;

import java.lang.foreign.MemorySegment;
import java.nio.ByteOrder;

import jdk.incubator.vector.IntVector;
import jdk.incubator.vector.VectorMask;
import jdk.incubator.vector.VectorSpecies;

/**
 * SIMD kernels for the Varka Date/Time MVP: DATE + INTEGER, DATE - INTEGER and DATEDIFF over
 * Arrow buffers (int32 days since epoch + bit-packed validity, bit set = valid).
 *
 * <p>All methods operate on raw addresses (`long`) so that generated bytecode can invoke them via
 * `invokestatic` with a primitive stack (see Task 4). The argument order below is therefore the
 * stack order the bytecode must push.
 *
 * <p>Validity contract: a source validity pointer is dereferenced only when
 * `0 < nullCount < length`; callers with a null-free or all-null source may pass `0L`. The
 * destination validity pointer is always required, and the kernel writes the output null bits.
 * Data values of null output rows are undefined.
 *
 * <p>Int32 arithmetic wraps on overflow, matching Spark's date expressions. Endianness is
 * little-endian (Arrow's in-memory layout). See sql/varka/PLAN_TASK_2.md.
 *
 * <h2>The shape of a kernel</h2>
 *
 * <p>These are the reference implementation for the kernels that follow them, so the order of
 * operations below is deliberate rather than incidental. A new kernel should keep it:
 *
 * <ol>
 *   <li><b>Return early on an empty batch.</b> There is nothing to write, and every step below
 *       assumes at least one row.</li>
 *   <li><b>Wrap each address at its nominal size</b> - {@code length * 4} bytes for data,
 *       {@code (length + 7) / 8} for a bitmap - with {@link VarkaVectorSupport#ofAddress}. That
 *       size is the only bounds check a kernel gets, because the caller hands over a bare
 *       {@code long}. Sizing a
 *       segment to whatever the underlying buffer happens to have allocated would turn reads
 *       past the end of the batch into silent successes.</li>
 *   <li><b>Zero the destination validity before any early return</b>, so that every path which
 *       leaves rows unwritten leaves them null. Both loops below only ever OR bits in; nothing
 *       clears one.</li>
 *   <li><b>Take the all-null shortcut</b> for each source whose {@code nullCount == length}: the
 *       result is entirely null and the zeroed destination validity already says so. This is
 *       also what lets a caller pass {@code 0L} for that source's validity address.</li>
 *   <li><b>Build a mask per lane group</b> from the source validity - or an all-true mask when
 *       the source has no nulls - and use it for the loads, the arithmetic and the store alike.
 *       Masked-off lanes are never read, so a null row cannot fault or contribute; with several
 *       sources, AND their masks so a row is valid only where all of them are.</li>
 *   <li><b>Run the vector loop to {@link VectorSpecies#loopBound} and finish with a masked
 *       epilogue</b> - the fewer than {@code lanes} rows no whole group covered, done as one
 *       more iteration of the same body rather than as a scalar loop beside it.
 *       {@link VectorSpecies#indexInRange} builds the bounds mask; AND it into the validity
 *       mask and the group is bounded on both counts at once, so a row past the batch is
 *       neither read nor written. Two things change with it and are easy to miss: the row
 *       count is no longer a lane width, so the validity bits go through
 *       {@link VarkaVectorSupport#partialValidityBitsAt} and
 *       {@link VarkaVectorSupport#orPartialValidityBitsAt} (the whole-group forms derive their
 *       byte span from the width and would read one byte for a nine-row group, or write past
 *       a nominally sized bitmap); and the loop body is now mirrored in two places, which the
 *       helpers below keep down to three lines. That is the whole reason to prefer this shape
 *       to a scalar tail: a scalar tail is a second, different lowering of the same
 *       arithmetic, and it has to agree row for row. {@code DateVectorOpsTest} checks each
 *       kernel against a scalar reference at sizes that straddle every lane and byte
 *       boundary, and {@code DateVectorOpsBitmapTest} walks every lane width the Vector API
 *       admits, including the ones this host cannot produce.</li>
 * </ol>
 *
 * <p>Three things are easy to get wrong and hard to see afterwards. The destination data of a
 * null row is undefined - never assert on it - because the masked store skips those lanes. Every
 * validity access has to be bounded by the lane group rather than by a machine word, or the
 * kernel reads past a short bitmap (see {@link VarkaVectorSupport#validityBitsAt}). And the
 * lane count is a property of the host, not a constant: it is 4 on aarch64 NEON and on x86
 * without AVX2, 8 on
 * AVX2 and 16 on AVX-512, so anything derived from it must be computed, never assumed.
 */
public final class DateVectorOps {

  private static final VectorSpecies<Integer> SPECIES = IntVector.SPECIES_PREFERRED;
  private static final ByteOrder ORDER = ByteOrder.LITTLE_ENDIAN;
  private DateVectorOps() {}

  /**
   * The epilogue's lane mask: this partial group's validity bits ANDed with the bounds mask
   * {@link VectorSpecies#indexInRange} builds, so one mask still drives the load, the
   * arithmetic and the store, and bounds the group by the batch as well as by validity. The
   * validity bits come from {@link VarkaVectorSupport#partialValidityBitsAt} because
   * {@code rows} is a row count here, not a lane width; see the class doc's step 5.
   *
   * <p><b>The epilogue lives in its own method, and the loops build their masks inline.</b>
   * Two cheaper-looking factorings were written first and both cost throughput on the
   * mixed-null path (task 24, measured with interleaved A/B runs). Sharing one mask helper
   * between the loop and the epilogue cost 24-50%: it puts {@code partialValidityBitsAt},
   * which contains a byte loop, inside what the hot loop has to inline. Leaving the epilogue
   * inline in the kernel method cost 8-40%, in proportion to how many times it calls this
   * helper - the epilogue's own Vector API calls compete with the loop's for C2's budget even
   * though the branch runs at most once per batch. Both are the house rule in
   * {@code sql/varka/AGENTS.md} arriving from a new direction: sibling methods, not longer
   * methods.
   */
  private static VectorMask<Integer> epilogueMask(
      MemorySegment validity, boolean hasNulls, long row, int rows, int length) {
    VectorMask<Integer> bounds = SPECIES.indexInRange((int) row, length);
    return hasNulls
        ? VectorMask.fromLong(SPECIES, partialValidityBitsAt(validity, row, rows)).and(bounds)
        : bounds;
  }

  /**
   * dst[i] = src[i] + daysOffset; dst null iff src null.
   *
   * @param srcData address of the source int32 day values.
   * @param srcValidity address of the source bit-packed validity; ignored (may be 0L) when
   *        {@code srcNullCount == 0} or {@code srcNullCount == length}.
   * @param srcNullCount number of null rows in the source.
   * @param dstData address of the destination int32 day values (length * 4 bytes).
   * @param dstValidity address of the destination bit-packed validity
   *        ((length + 7) / 8 bytes); always required.
   * @param length number of rows.
   * @param daysOffset the number of days to add (runtime value, never inlined at codegen).
   */
  public static void vectorAddDays(
      long srcData, long srcValidity, int srcNullCount,
      long dstData, long dstValidity, int length, int daysOffset) {
    // (1) An empty batch has nothing to write, and everything below assumes at least one row.
    if (length <= 0) {
      return;
    }
    // (2) Nominal sizes only: these bounds are what keep the kernel inside the batch.
    MemorySegment src = ofAddress(srcData, length * 4L);
    MemorySegment dst = ofAddress(dstData, length * 4L);
    MemorySegment dstValiditySeg = ofAddress(dstValidity, (length + 7) / 8L);
    // (3) Zero before any return below, so rows this kernel does not write come out null.
    zero(dstValiditySeg);
    // (4) All-null source: the result is all-null, which the zeroed validity already says.
    if (srcNullCount == length) {
      return;
    }
    // The source validity is mapped only when the source actually has nulls - the branch below
    // never touches it otherwise - which is what lets a null-free caller pass 0L for it.
    boolean hasNulls = srcNullCount > 0;
    MemorySegment validity = hasNulls ? ofAddress(srcValidity, (length + 7) / 8L) : null;
    // The offset is a runtime value broadcast into every lane, never folded in at codegen: one
    // assembled kernel serves every literal a query might use.
    IntVector offsetVec = IntVector.broadcast(SPECIES, daysOffset);

    // (5) and (6): one lane group per iteration, up to the last whole group.
    long loopBound = SPECIES.loopBound(length);
    int lanes = SPECIES.length();
    long i = 0;
    for (; i < loopBound; i += lanes) {
      // The mask drives the load, the add and the store together, so a null lane is never read
      // (it cannot fault on a poisoned value) and never written (its dst data stays undefined).
      VectorMask<Integer> mask = hasNulls
          ? VectorMask.fromLong(SPECIES, validityBitsAt(validity, i, lanes))
          : VectorMask.fromLong(SPECIES, -1L);  // all-true mask
      long byteOffset = i * 4L;
      IntVector va = IntVector.fromMemorySegment(SPECIES, src, byteOffset, ORDER, mask);
      // Lane-wise int add: wraps on overflow, which is what Spark's DateAdd does too.
      va.add(offsetVec, mask).intoMemorySegment(dst, byteOffset, ORDER, mask);
      // The same mask is this group's output validity: dst is null exactly where src was.
      orValidityBitsAt(dstValiditySeg, i, mask.toLong(), lanes);
    }
    // The epilogue: the fewer than `lanes` rows no whole group covered, as one more iteration
    // of the body above with the bounds mask ANDed in (class doc, step 5). Its own method, for
    // the reason the class doc gives - it must not be inlined into the loop's.
    if (i < length) {
      addDaysEpilogue(src, dst, dstValiditySeg, validity, hasNulls, i, length, offsetVec);
    }
  }

  /** {@link #vectorAddDays}'s final partial lane group; see the class doc's step 5. */
  private static void addDaysEpilogue(MemorySegment src, MemorySegment dst,
      MemorySegment dstValiditySeg, MemorySegment validity, boolean hasNulls,
      long i, int length, IntVector offsetVec) {
    int rows = (int) (length - i);
    VectorMask<Integer> mask = epilogueMask(validity, hasNulls, i, rows, length);
    long byteOffset = i * 4L;
    IntVector va = IntVector.fromMemorySegment(SPECIES, src, byteOffset, ORDER, mask);
    va.add(offsetVec, mask).intoMemorySegment(dst, byteOffset, ORDER, mask);
    orPartialValidityBitsAt(dstValiditySeg, i, mask.toLong(), rows);
  }

  /**
   * dst[i] = src[i] - daysOffset; dst null iff src null. Delegates to {@link #vectorAddDays}
   * with the negated offset.
   *
   * <p>Subtracting and adding the negation agree for every {@code int}, including
   * {@code Integer.MIN_VALUE}, whose negation is itself: both are the same wrap modulo 2^32, and
   * that is the arithmetic Spark's {@code DateSub} performs as well. {@code VarkaDifferentialSuite}
   * pins the boundary offsets against a scalar oracle.
   */
  public static void vectorSubDays(
      long srcData, long srcValidity, int srcNullCount,
      long dstData, long dstValidity, int length, int daysOffset) {
    vectorAddDays(srcData, srcValidity, srcNullCount, dstData, dstValidity, length, -daysOffset);
  }

  /**
   * dst[i] = a[i] - b[i]; dst null iff a or b is null (DATEDIFF).
   *
   * @param dataA address of the first source int32 day values (end date).
   * @param validityA address of the first source validity; ignored (may be 0L) when
   *        {@code nullCountA == 0} or {@code nullCountA == length}.
   * @param nullCountA number of null rows in the first source.
   * @param dataB address of the second source int32 day values (start date).
   * @param validityB address of the second source validity; ignored (may be 0L) when
   *        {@code nullCountB == 0} or {@code nullCountB == length}.
   * @param nullCountB number of null rows in the second source.
   * @param dstData address of the destination int32 day values (length * 4 bytes).
   * @param dstValidity address of the destination bit-packed validity
   *        ((length + 7) / 8 bytes); always required.
   * @param length number of rows.
   */
  public static void vectorDateDiff(
      long dataA, long validityA, int nullCountA,
      long dataB, long validityB, int nullCountB,
      long dstData, long dstValidity, int length) {
    if (length <= 0) {
      return;
    }
    // The same six steps as vectorAddDays, with one source more. See the class javadoc.
    MemorySegment a = ofAddress(dataA, length * 4L);
    MemorySegment b = ofAddress(dataB, length * 4L);
    MemorySegment dst = ofAddress(dstData, length * 4L);
    MemorySegment dstValiditySeg = ofAddress(dstValidity, (length + 7) / 8L);
    zero(dstValiditySeg);
    // Either side being all-null makes every output row null, so one shortcut covers both.
    if (nullCountA == length || nullCountB == length) {
      return;
    }
    boolean hasNullA = nullCountA > 0;
    boolean hasNullB = nullCountB > 0;
    MemorySegment validityAseg =
        hasNullA ? ofAddress(validityA, (length + 7) / 8L) : null;
    MemorySegment validityBseg =
        hasNullB ? ofAddress(validityB, (length + 7) / 8L) : null;

    long loopBound = SPECIES.loopBound(length);
    int lanes = SPECIES.length();
    long i = 0;
    for (; i < loopBound; i += lanes) {
      // A row survives only where both inputs are valid, so the two masks are ANDed - and the
      // result is again both the store mask and the output validity for this group.
      VectorMask<Integer> maskA = hasNullA
          ? VectorMask.fromLong(SPECIES, validityBitsAt(validityAseg, i, lanes))
          : VectorMask.fromLong(SPECIES, -1L);  // all-true mask
      VectorMask<Integer> maskB = hasNullB
          ? VectorMask.fromLong(SPECIES, validityBitsAt(validityBseg, i, lanes))
          : VectorMask.fromLong(SPECIES, -1L);  // all-true mask
      // A row survives only where both inputs are valid, so the two masks are ANDed - and the
      // result is again both the store mask and the output validity for this group.
      VectorMask<Integer> mask = maskA.and(maskB);
      long byteOffset = i * 4L;
      IntVector va = IntVector.fromMemorySegment(SPECIES, a, byteOffset, ORDER, mask);
      IntVector vb = IntVector.fromMemorySegment(SPECIES, b, byteOffset, ORDER, mask);
      va.sub(vb, mask).intoMemorySegment(dst, byteOffset, ORDER, mask);
      orValidityBitsAt(dstValiditySeg, i, mask.toLong(), lanes);
    }
    // The epilogue; see vectorAddDays and the class doc's step 5.
    if (i < length) {
      dateDiffEpilogue(a, b, dst, dstValiditySeg, validityAseg, hasNullA, validityBseg,
          hasNullB, i, length);
    }
  }

  /**
   * {@link #vectorDateDiff}'s final partial lane group. The bounds mask only has to reach one
   * of the two operand masks - they are ANDed - but {@link #epilogueMask} puts it in both,
   * because a reader checking one side should not have to find the bound on the other.
   */
  private static void dateDiffEpilogue(MemorySegment a, MemorySegment b, MemorySegment dst,
      MemorySegment dstValiditySeg, MemorySegment validityAseg, boolean hasNullA,
      MemorySegment validityBseg, boolean hasNullB, long i, int length) {
    int rows = (int) (length - i);
    VectorMask<Integer> mask = epilogueMask(validityAseg, hasNullA, i, rows, length)
        .and(epilogueMask(validityBseg, hasNullB, i, rows, length));
    long byteOffset = i * 4L;
    IntVector va = IntVector.fromMemorySegment(SPECIES, a, byteOffset, ORDER, mask);
    IntVector vb = IntVector.fromMemorySegment(SPECIES, b, byteOffset, ORDER, mask);
    va.sub(vb, mask).intoMemorySegment(dst, byteOffset, ORDER, mask);
    orPartialValidityBitsAt(dstValiditySeg, i, mask.toLong(), rows);
  }

}
