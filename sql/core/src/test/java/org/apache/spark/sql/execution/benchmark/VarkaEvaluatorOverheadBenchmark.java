/**
 * What a Varka evaluator costs per batch, apart from what its kernel costs per row (VARKA-251).
 *
 * <p>Every Varka node hands each input batch to an evaluator, which checks the batch can take the
 * kernel, fills the kernel's argument arrays, allocates the output vectors, runs the kernel, and
 * tracks the output batch for release. That work is per batch, so it shows where batches are
 * small. VARKA-251 splits {@code VarkaEvaluatorBase}, which does all of it, into Java components,
 * and this file is the proof that the split costs nothing per batch: committed first against the
 * unchanged code, then regenerated by the split.
 *
 * <p>The evaluators are driven directly, as {@code VarkaProjectExecSuite} drives them, over Arrow
 * batches built once and read by every iteration, inside a task context of their own; no Spark
 * job runs. Each benchmark counts its batches as its values, so the "Per Row(ns)" column is
 * nanoseconds per batch. Four shapes, one per path through the per-batch machinery:
 *
 * <pre>
 *   int lane       date_add(d, 3), a projection
 *   long lane      least(l, 5000000000), a projection over a bigint, the long literal table
 *   filter         d &gt; DATE'2000-01-01', the selection bitmap instead of output vectors
 *   derived input  trunc(d, fmt), the format parsed into the evaluator's scratch per batch
 * </pre>
 *
 * <p>at 1, 16 and 1024 rows a batch. Every case checks afterwards that each of its batches went
 * through the kernel, so a shape that stopped fusing fails the run instead of timing the row
 * path; the dry run, {@code -Dvarka.bench.dryRun=true}, builds the batches and times nothing, so
 * it skips that check, as a run filtered with {@code -Dvarka.bench.only} does.
 *
 * <p>To run this benchmark:
 * <pre>
 *   dev/varka_bench_regen.sh sql VarkaEvaluatorOverheadBenchmark
 * </pre>
 */
public class VarkaEvaluatorOverheadBenchmark extends VarkaSqlBenchmarkBase {

  private static final List<String> FORMATS = List.of("YEAR", "MONTH", "QUARTER", "WEEK");

  /** The batch sizes and how many batches of each a task reads. */
  private record Size(int rows, int batches) {}

  /** One shape: its name, its input columns, and a fresh evaluator over them with its metrics. */
  private record Shape(String name, List<Attribute> input,
      Function<VarkaExecMetrics, PartitionEvaluator<ColumnarBatch, ColumnarBatch>> evaluator) {}

  /** A case's shape, its input batches and the metrics its evaluators count into. */
  private record Case(Shape shape, List<ColumnarBatch> inputs, VarkaExecMetrics metrics) {}

  private static AttributeReference attribute(String name, DataType type) {
    return new AttributeReference(name, type, true, Metadata.empty(),
        NamedExpression.newExprId(), seq(List.of()));
  }

  private Shape project(Expression expression, List<Attribute> input) {
    SparkContext sc = spark().sparkContext();
    NamedExpression out = new Alias(expression, "out", NamedExpression.newExprId(),
        seq(List.of()), Option.empty(), seq(List.of()));
    return new Shape(expression.sql(), input, metrics -> new VarkaProjectEvaluatorFactory(
        seq(List.of(out)), seq(input), false, Option.empty(),
        SQLMetrics.createMetric(sc, "rows"), SQLMetrics.createMetric(sc, "batches"), metrics,
        VarkaSessionEmit.DEFAULTS, false, false).createEvaluator());
  }

  private Shape filter(Expression condition, List<Attribute> input) {
    SparkContext sc = spark().sparkContext();
    return new Shape("filter " + condition.sql(), input, metrics -> new VarkaFilterEvaluatorFactory(
        condition, seq(input), false, Option.empty(),
        SQLMetrics.createMetric(sc, "rows"), SQLMetrics.createMetric(sc, "batches"), metrics,
        VarkaSessionEmit.DEFAULTS, false, Option.empty(), false, true).createEvaluator());
  }

  private List<Shape> shapes() {
    AttributeReference d = attribute("d", DataTypes.DateType);
    AttributeReference l = attribute("l", DataTypes.LongType);
    AttributeReference fmt = attribute("fmt", DataTypes.StringType);
    return List.of(
        project(new DateAdd(d, Literal.create(3, DataTypes.IntegerType)), List.of(d)),
        project(new Least(seq(List.of(l, Literal.create(5_000_000_000L, DataTypes.LongType)))),
            List.of(l)),
        filter(new GreaterThan(d, Literal.create(java.sql.Date.valueOf("2000-01-01"),
            DataTypes.DateType)), List.of(d)),
        project(new TruncDate(d, fmt), List.of(d, fmt)));
  }

  /** A batch of {@code rows} rows of {@code input}'s columns, every tenth value null. */
  private static ColumnarBatch batch(List<Attribute> input, int rows, int seed,
      BufferAllocator allocator) {
    var columns = new ColumnVector[input.size()];
    for (int c = 0; c < columns.length; c++) {
      Attribute a = input.get(c);
      FieldVector vector = ArrowUtils.toArrowField(a.name(), a.dataType(), true, null, false,
          Metadata.empty(), false).createVector(allocator);
      switch (vector) {
        case VarCharVector v -> v.allocateNew(rows * 8L, rows);
        case BaseFixedWidthVector v -> v.allocateNew(rows);
        default -> throw new IllegalArgumentException("no allocation for a " + vector.getClass());
      }
      for (int i = 0; i < rows; i++) {
        int k = seed * rows + i;
        boolean isNull = k % 10 == 9;
        switch (vector) {
          case DateDayVector v when isNull -> v.setNull(i);
          case DateDayVector v -> v.setSafe(i, 10000 + k % 20000);
          case BigIntVector v when isNull -> v.setNull(i);
          case BigIntVector v -> v.setSafe(i, k * 7L);
          // The format is never null: a null format is a null answer the kernel never sees.
          case VarCharVector v ->
              v.setSafe(i, FORMATS.get(k % FORMATS.size()).getBytes(StandardCharsets.UTF_8));
          default -> throw new IllegalArgumentException("no values for a " + vector.getClass());
        }
      }
      vector.setValueCount(rows);
      columns[c] = new ArrowColumnVector(vector);
    }
    return new ColumnarBatch(columns, rows);
  }

  /**
   * One task's worth: a fresh evaluator over {@code inputs}, every output batch taken, which
   * releases the one before it, then the task completed. The kernel class comes from the shape
   * cache after the first task, as it does for every task of a query.
   */
  private static long runTask(Case c) {
    // `empty`, `setTaskContext` and `unset` are private[spark] or protected[spark], which scalac
    // gives no static forwarder.
    TaskContextImpl context = TaskContext$.MODULE$.empty();
    TaskContext$.MODULE$.setTaskContext(context);
    try {
      scala.collection.Iterator<ColumnarBatch> out = c.shape().evaluator().apply(c.metrics())
          .eval(0, seq(List.of(CollectionConverters.asScala(c.inputs().iterator()))));
      long rows = 0;
      while (out.hasNext()) {
        rows += out.next().numRows();
      }
      context.markTaskCompleted(Option.empty());
      return rows;
    } finally {
      TaskContext$.MODULE$.unset();
    }
  }

  @Override
  public void runBenchmarkSuite(String[] mainArgs) {
    BufferAllocator allocator = ArrowUtils.rootAllocator().newChildAllocator("varka-overhead", 0,
        Long.MAX_VALUE);
    try {
      List<Shape> shapes = shapes();
      for (Size size : List.of(new Size(1, 20_000), new Size(16, 20_000), new Size(1024, 2000))) {
        section("Varka evaluator per batch, " + size.rows() + " rows a batch",
            () -> sizeTable(shapes, size, allocator));
      }
    } finally {
      allocator.close();
    }
  }

  private void sizeTable(List<Shape> shapes, Size size, BufferAllocator allocator) {
    int batches = size.batches();
    VarkaBenchmark benchmark = benchmark(
        size.rows() + " rows a batch, ns per batch", batches).build();
    var cases = new ArrayList<Case>(shapes.size());
    try {
      for (Shape shape : shapes) {
        var inputs = new ArrayList<ColumnarBatch>(batches);
        for (int b = 0; b < batches; b++) {
          inputs.add(batch(shape.input(), size.rows(), b, allocator));
        }
        VarkaExecMetrics metrics = VarkaExecMetrics.builder()
            .varkaBatches(SQLMetrics.createMetric(spark().sparkContext(), "varka")).build();
        var c = new Case(shape, inputs, metrics);
        cases.add(c);
        benchmark.addCase(shape.name(), i -> runTask(c));
      }
      runCases(benchmark);
      // A dry run times no case, and -Dvarka.bench.only may drop some, leaving them uncounted.
      if (!dryRun() && only().isEmpty()) {
        for (Case c : cases) {
          long served = c.metrics().varkaBatches().value();
          // Every iteration served every batch by the kernel, the warm-up iterations too.
          require(served > 0 && served % batches == 0, c.shape().name() + ": " + served
              + " of its batches took the kernel, not a multiple of " + batches);
        }
      }
    } finally {
      for (Case c : cases) {
        c.inputs().forEach(ColumnarBatch::close);
      }
    }
  }
}
